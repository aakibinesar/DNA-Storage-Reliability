_ORACLE_SEED_OFFSET      = 3000   # oracle marginal-benefit estimation
_EVAL_SEED_OFFSET        = 1000   # main allocation evaluation runs
_DELTA_SEED_OFFSET       = 2000   # delta-sensitivity evaluation runs
_ORACLE_HARM_SEED_OFFSET = 5000   # oracle marginal-harm estimation (R4 fix)


# -- Oracle marginal-benefit estimation (R2) ----------------------------------

def estimate_marginal_benefits(
    sequences:          List[str],
    true_failure_freq:  np.ndarray,
    channel,
    coverage:           int,
    l_rs_default:       int,
    delta:              int,
    n_runs:             int = 30,
    base_seed:          int = 0,
    oracle_seed_offset: int = _ORACLE_SEED_OFFSET,
    l_rs_max:           int = 16,
) -> np.ndarray:
    """Estimate per-sequence marginal failure reduction from one extra delta of parity.

    Computes: marginal_benefit_i = p_i(l_rs_default) - p_i(l_rs_default + delta)

    p_i(l_rs_default) is taken from true_failure_freq (already estimated during
    dataset generation with seeds base_seed + 0..n_runs-1).
    p_i(l_rs_default + delta) is estimated here with seeds
    base_seed + oracle_seed_offset + 0..n_runs-1 — a non-overlapping range.

    Positive values indicate sequences that genuinely benefit from promotion to
    higher parity; zero or negative values indicate sequences already past the
    point of diminishing returns (over-failure regime).

    Parameters
    ----------
    oracle_seed_offset : seed offset relative to base_seed; use different values per
                         delta sweep to keep oracle-estimation seeds non-overlapping.
    """
    from consensus_voter import majority_vote_consensus, count_errors

    N      = len(sequences)
    l_high = min(l_rs_default + delta, l_rs_max)

    failures_high = np.zeros(N, dtype=np.float64)
    for run_idx in range(n_runs):
        run_channel = channel.clone(seed=base_seed + oracle_seed_offset + run_idx)
        for i, seq in enumerate(sequences):
            reads      = run_channel.simulate(seq, coverage)
            consensus  = majority_vote_consensus(reads, len(seq))
            stats      = count_errors(seq, consensus)
            if stats['byte_errors'] > l_high // 2:
                failures_high[i] += 1

    p_high = failures_high / n_runs
    return true_failure_freq - p_high   # positive = extra parity reduces failures


# -- Oracle marginal-harm estimation (R4) --------------------------------------

def estimate_marginal_harm(
    sequences:          List[str],
    true_failure_freq:  np.ndarray,
    channel,
    coverage:           int,
    l_rs_default:       int,
    delta:              int,
    n_runs:             int = 30,
    base_seed:          int = 0,
    harm_seed_offset:   int = _ORACLE_HARM_SEED_OFFSET,
    l_rs_min:           int = 4,
) -> np.ndarray:
    """Estimate per-sequence marginal failure increase from losing delta parity.

    Computes: marginal_harm_i = p_i(l_rs_default - delta) - p_i(l_rs_default)

    Symmetric counterpart to estimate_marginal_benefits(). By RS decode-failure
    monotonicity in parity bytes (for a fixed error realisation, fewer parity
    bytes can only maintain or increase decode-failure probability, never
    reduce it), this is expected to be >= 0.

    This is the piece the original R2/R3 fixes were missing (R4): a sequence
    can have near-zero benefit from ADDING parity for two very different
    reasons -- it's already safe (demoting it is harmless), or it's already
    deep in the saturated/over-failure regime (demoting it is actively
    harmful, since it needs protection, not less of it). marginal_benefits
    alone cannot distinguish these; marginal_harm is what tells them apart,
    and is required for oracle_allocation_greedy_swap in mechanism.py.

    Parameters
    ----------
    harm_seed_offset : seed offset relative to base_seed; use different values
                       per delta sweep to keep estimation seeds non-overlapping
                       with each other and with estimate_marginal_benefits.
    """
    from consensus_voter import majority_vote_consensus, count_errors

    N     = len(sequences)
    l_low = max(l_rs_default - delta, l_rs_min)

    failures_low = np.zeros(N, dtype=np.float64)
    for run_idx in range(n_runs):
        run_channel = channel.clone(seed=base_seed + harm_seed_offset + run_idx)
        for i, seq in enumerate(sequences):
            reads      = run_channel.simulate(seq, coverage)
            consensus  = majority_vote_consensus(reads, len(seq))
            stats      = count_errors(seq, consensus)
            if stats['byte_errors'] > l_low // 2:
                failures_low[i] += 1

    p_low = failures_low / n_runs
    return p_low - true_failure_freq   # positive = removing parity increases failures


# -- Paired oracle estimation (fix: replaces 3 independent simulations) -------

def estimate_paired_marginal_effects(
    sequences:    List[str],
    channel,
    coverage:     int,
    l_rs_default: int,
    delta:        int,
    n_runs:       int = 30,
    base_seed:    int = 0,
    seed_offset:  int = _ORACLE_SEED_OFFSET,
    l_rs_min:     int = 4,
    l_rs_max:     int = 16,
):
    """Paired marginal-benefit and marginal-harm estimate from ONE shared
    channel-noise draw per run (fix for the noise-inflating bug where the
    default/high/low parity outcomes were each estimated from independently
    resimulated channel noise, on top of the three already being independent
    of each other -- summing three independent noise sources into each
    difference rather than one common-random-numbers draw evaluated at three
    thresholds). Every run reuses the exact same synthesized byte-error count
    per sequence for all three thresholds, so subtracting them cancels the
    shared run-to-run noise instead of adding to it -- the same technique
    _precompute_byte_errors already uses for the main evaluation loop,
    applied here to the oracle's own estimation step.

    Returns
    -------
    (marginal_benefit, marginal_harm) : each an array of shape (N,)
        marginal_benefit = p(default) - p(default + delta)
        marginal_harm    = p(default - delta) - p(default)
    """
    from consensus_voter import majority_vote_consensus, count_errors

    N      = len(sequences)
    l_high = min(l_rs_default + delta, l_rs_max)
    l_low  = max(l_rs_default - delta, l_rs_min)

    failures_default = np.zeros(N, dtype=np.float64)
    failures_high    = np.zeros(N, dtype=np.float64)
    failures_low     = np.zeros(N, dtype=np.float64)

    for run_idx in range(n_runs):
        run_channel = channel.clone(seed=base_seed + seed_offset + run_idx)
        for i, seq in enumerate(sequences):
            reads      = run_channel.simulate(seq, coverage)
            consensus  = majority_vote_consensus(reads, len(seq))
            stats      = count_errors(seq, consensus)
            byte_errors = stats['byte_errors']
            if byte_errors > l_rs_default // 2:
                failures_default[i] += 1
            if byte_errors > l_high // 2:
                failures_high[i] += 1
            if byte_errors > l_low // 2:
                failures_low[i] += 1

    p_default = failures_default / n_runs
    p_high    = failures_high / n_runs
    p_low     = failures_low / n_runs

    marginal_benefit = p_default - p_high
    marginal_harm    = p_low - p_default
    return marginal_benefit, marginal_harm


# -- Soft (kernel-smoothed) marginal effects for benefit-model training -------

def estimate_soft_marginal_effects(
    sequences:    List[str],
    channel,
    coverage:     int,
    l_rs_default: int,
    delta:        int,
    n_runs:       int = 30,
    base_seed:    int = 0,
    seed_offset:  int = _ORACLE_SEED_OFFSET,
    l_rs_min:     int = 4,
    l_rs_max:     int = 16,
    temperature:  float = 1.0,
):
    """Continuous, kernel-smoothed counterpart to estimate_paired_marginal_effects().

    Motivation
    ----------
    The hard-threshold version only learns anything from a run whose byte-error
    count lands EXACTLY at the boundary between two correction capacities (e.g.
    at delta=2 with l_rs_default=8, only byte_errors==5 distinguishes "passes
    at default+delta" from "fails at default"). Every other run -- comfortably
    passing or comfortably failing either way -- contributes nothing to the
    label. Diagnosed directly on sub20_k3_simple: 62% of sequences got an
    exactly-zero benefit label at delta=2 purely because none of their 30 runs
    happened to land on that single integer, not because their true benefit is
    zero -- a label with almost no usable resolution for training a model.

    Fix: replace the hard indicator 1(byte_errors > capacity) with a smoothed
    sigmoid 1/(1+exp(-(byte_errors-capacity-0.5)/temperature)), which is ~1
    well above the threshold, ~0 well below it, and varies smoothly in between.
    A run with byte_errors two units below the boundary now contributes a
    small-but-nonzero amount of information instead of exactly zero, so the
    same 30 runs yield a far less discretized, better-conditioned label. This
    is used ONLY for building training/validation labels for the benefit
    model -- the oracle's actual allocation decisions and every reported OFR
    figure keep using the true hard RS-decode pass/fail criterion, since that
    is the real physical rule being modeled; the smoothing is a training-label
    device, not a change to what "failure" means operationally.

    Returns
    -------
    (marginal_benefit, marginal_harm) : each an array of shape (N,), continuous.
    """
    from consensus_voter import majority_vote_consensus, count_errors

    N      = len(sequences)
    l_high = min(l_rs_default + delta, l_rs_max)
    l_low  = max(l_rs_default - delta, l_rs_min)
    cap_default = l_rs_default // 2
    cap_high    = l_high // 2
    cap_low     = l_low // 2

    def _soft_fail(byte_errors, capacity):
        return 1.0 / (1.0 + np.exp(-(byte_errors - capacity - 0.5) / temperature))

    soft_default = np.zeros(N, dtype=np.float64)
    soft_high    = np.zeros(N, dtype=np.float64)
    soft_low     = np.zeros(N, dtype=np.float64)

    for run_idx in range(n_runs):
        run_channel = channel.clone(seed=base_seed + seed_offset + run_idx)
        for i, seq in enumerate(sequences):
            reads       = run_channel.simulate(seq, coverage)
            consensus   = majority_vote_consensus(reads, len(seq))
            stats       = count_errors(seq, consensus)
            byte_errors = stats['byte_errors']
            soft_default[i] += _soft_fail(byte_errors, cap_default)
            soft_high[i]    += _soft_fail(byte_errors, cap_high)
            soft_low[i]     += _soft_fail(byte_errors, cap_low)

    p_default = soft_default / n_runs
    p_high    = soft_high / n_runs
    p_low     = soft_low / n_runs

    marginal_benefit = p_default - p_high
    marginal_harm    = p_low - p_default
    return marginal_benefit, marginal_harm


# -- Deployable tier-fraction selection (fix: no oracle/test-label info) ------

def select_tier_fraction_on_validation(
    sequences_val:        List[str],
    calibrated_risk_val:  np.ndarray,
    channel,
    coverage:             int,
    l_rs_default:         int,
    delta:                int,
    l_rs_min:             int = 4,
    l_rs_max:             int = 16,
    tier_grid:            tuple = (0.05, 0.10, 0.20, 0.30),
    n_runs:               int = 30,
    base_seed:            int = 0,
    seed_offset:          int = 9000,
):
    """Choose the reallocation budget (tier_fraction) that minimises OFR on
    the validation set, using only the model's own calibrated risk ranking on
    validation sequences -- no oracle-derived n_star, no test labels (fix:
    the old deployable experiment borrowed the oracle's privileged budget
    size instead of choosing its own). The choice is frozen here, before any
    test-set evaluation happens.

    Returns
    -------
    (best_tier_fraction, mean_ofr_by_candidate) -- the second value is a
    dict for logging/diagnostics.
    """
    from mechanism import AllocationMechanism

    alloc_mech = AllocationMechanism(l_rs_default, delta, l_rs_min, l_rs_max)
    allocs = {tf: alloc_mech.allocate(calibrated_risk_val, tier_fraction=tf)
              for tf in tier_grid}

    ofr_sums = {tf: 0.0 for tf in tier_grid}
    for run_idx in range(n_runs):
        run_channel = channel.clone(seed=base_seed + seed_offset + run_idx)
        byte_errors = _precompute_byte_errors(sequences_val, run_channel, coverage)
        for tf in tier_grid:
            ofr_sums[tf] += np.mean(byte_errors > (allocs[tf] // 2))

    mean_ofr = {tf: ofr_sums[tf] / n_runs for tf in tier_grid}
    best_tf  = min(mean_ofr, key=mean_ofr.get)
    return best_tf, mean_ofr


# -- Common random number helper (R3) -----------------------------------------

def _precompute_byte_errors(
    sequences: List[str],
    channel,
    coverage:  int,
) -> np.ndarray:
    """Run the channel once for all sequences; return per-sequence byte-error counts.

    All allocation conditions evaluate against this shared array so that differences
    in OFR reflect allocation policy alone, not RNG variation (CRN / R3 fix).
    """
    from consensus_voter import majority_vote_consensus, count_errors

    N = len(sequences)
    byte_errors = np.zeros(N, dtype=np.int32)
    for i, seq in enumerate(sequences):
        reads          = channel.simulate(seq, coverage)
        consensus      = majority_vote_consensus(reads, len(seq))
        stats          = count_errors(seq, consensus)
        byte_errors[i] = stats['byte_errors']
    return byte_errors


# -- Main allocation experiment ------------------------------------------------

def run_allocation_experiment(
    sequences:         List[str],
    true_failure_freq: np.ndarray,
    marginal_benefits: np.ndarray,
    marginal_harm:     np.ndarray,
    calibrated_risk:   np.ndarray,
    raw_risk:          np.ndarray,
    channel,
    coverage:          int,
    l_rs_default:      int,
    delta:             int,
    n_runs:            int = 30,
    base_seed:         int = 0,
    l_rs_min:          int = 4,
    l_rs_max:          int = 16,
    verbose:           bool = False,
    tier_fraction_deployable: float = None,
    benefit_scores:    np.ndarray = None,
    tier_fraction_benefit: float = None,
) -> Dict[str, np.ndarray]:
    """Run all four allocation conditions across M independent simulator runs.

    R2 fix: oracle ranks sequences by marginal_benefits = p(default) - p(default+delta)
            rather than by baseline failure_freq.  Call estimate_marginal_benefits()
            first to compute marginal_benefits, then pass the result here.

    R3 fix: within each run, one channel clone generates byte errors for all
            sequences (common random numbers).  All eight conditions evaluate
            against the identical noise realisation — only the parity allocation
            differs.

    R4 fix: the oracle previously ranked by marginal_benefits alone and forced
            exactly N//2 promotions/demotions regardless of how many sequences
            actually had a positive marginal benefit -- this let it demote
            already-failing sequences (whose benefit-from-adding is near zero
            for the wrong reason: they're saturated, not safe) and empirically
            lost to uniform in 66/84 production configs. Now the oracle uses
            oracle_allocation_greedy_swap(), which pairs the best promotion
            candidate with the least-harmed demotion candidate and stops the
            moment a swap is no longer net-beneficial -- this guarantees
            oracle OFR <= uniform OFR by construction. The resulting swap
            count (n_star) is then used as the tier size for the model and
            every rule-based baseline, so all conditions share the same
            oracle-determined budget and differ only in ranking quality.

    R10 fix: four rule-based baselines (gc_dev, hp, composite, random) are
             evaluated alongside the ML conditions so the paper can claim
             ML beats rule-based baselines.

    Fairness fix: the oracle-sized conditions above (xgb_cal, xgb_raw, and
    every rule-based baseline) all share the oracle's own n_star/N budget --
    useful for isolating *ranking quality* from *budget size*, but it means
    the "deployable" model is secretly told how many sequences to reallocate
    by a privileged, test-label-derived oracle. When tier_fraction_deployable
    is provided (chosen beforehand on validation data only, see
    select_tier_fraction_on_validation()), this function additionally
    computes a genuinely fair "*_deployable" condition for xgb_cal and every
    baseline, sharing the SAME validation-chosen budget across all of them
    with no oracle or test-label information anywhere in the choice. The
    oracle-sized conditions are kept as-is and should be read as a diagnostic
    ranking-quality comparison, not the deployable claim.

    Parameters
    ----------
    marginal_benefits : array (N,) — pre-computed from estimate_paired_marginal_effects().
    marginal_harm      : array (N,) — pre-computed from estimate_paired_marginal_effects().
    tier_fraction_deployable : optional fixed budget fraction, chosen on
        validation data only, for the fair "*_deployable" conditions.
    benefit_scores : optional (N,) predictions from the Part B benefit-aware
        model (models/train_benefit_model.py) on the test sequences. Ranked
        the same way as calibrated_risk -- highest score promoted, lowest
        demoted -- since a high benefit-model score means "this sequence
        benefits most from added parity" just as a high risk-model score
        means "this sequence is most likely to fail," and both should be
        promoted. When provided along with tier_fraction_benefit, adds the
        'ofr_benefit_model_deployable' condition: does ranking by predicted
        marginal benefit (chosen and sized entirely on validation data, no
        oracle or test-label information) actually reduce OFR more than
        ranking by predicted failure risk under the same fair budget?
    tier_fraction_benefit : validation-chosen budget fraction for the
        benefit-model condition (see select_tier_fraction_on_validation()).

    Returns
    -------
    dict with keys 'ofr_uniform', 'ofr_oracle', 'ofr_xgb_cal', 'ofr_xgb_raw',
    'ofr_gc_dev', 'ofr_hp', 'ofr_composite', 'ofr_random' (all diagnostic,
    oracle-sized budget), plus, when tier_fraction_deployable is given,
    'ofr_xgb_cal_deployable', 'ofr_gc_dev_deployable', 'ofr_hp_deployable',
    'ofr_composite_deployable', 'ofr_random_deployable' (fair, validation-
    sized budget), plus, when benefit_scores/tier_fraction_benefit are given,
    'ofr_benefit_model_deployable' -- each an array of shape (n_runs,).
    """
    from mechanism import AllocationMechanism, uniform_allocation, oracle_allocation_greedy_swap
    from baselines import get_baseline_allocations

    N             = len(sequences)
    l_rs_uniform  = uniform_allocation(N, l_rs_default)
    alloc         = AllocationMechanism(l_rs_default, delta, l_rs_min, l_rs_max)
    l_rs_oracle, n_star = oracle_allocation_greedy_swap(
        marginal_benefits, marginal_harm, l_rs_default, delta, l_rs_min, l_rs_max,
        n_runs=n_runs,
    )
    tier_fraction = n_star / N if N > 0 else 0.0
    if verbose:
        print(f"  [allocation] Oracle made {n_star}/{N} swaps clearing the noise floor "
              f"({tier_fraction:.1%} promoted/demoted)")
    l_rs_xgb_cal  = alloc.allocate(calibrated_risk, tier_fraction=tier_fraction)
    l_rs_xgb_raw  = alloc.allocate(raw_risk, tier_fraction=tier_fraction)

    # R10: rule-based baselines — allocations computed once from sequence features
    baseline_allocs = get_baseline_allocations(
        sequences, l_rs_default, delta, l_rs_min, l_rs_max,
        random_seed=base_seed + 8000, tier_fraction=tier_fraction,
    )

    # Fairness fix: fair, validation-sized budget conditions (no oracle/test info)
    have_deployable = tier_fraction_deployable is not None
    if have_deployable:
        l_rs_xgb_cal_dep = alloc.allocate(calibrated_risk, tier_fraction=tier_fraction_deployable)
        baseline_allocs_dep = get_baseline_allocations(
            sequences, l_rs_default, delta, l_rs_min, l_rs_max,
            random_seed=base_seed + 8100, tier_fraction=tier_fraction_deployable,
        )
        if verbose:
            print(f"  [allocation] Deployable budget (validation-chosen): "
                  f"{tier_fraction_deployable:.1%} promoted/demoted")

    # Part B: benefit-aware model deployable condition (fair, its own budget)
    have_benefit = benefit_scores is not None and tier_fraction_benefit is not None
    if have_benefit:
        l_rs_benefit_dep = alloc.allocate(benefit_scores, tier_fraction=tier_fraction_benefit)
        if verbose:
            print(f"  [allocation] Benefit-model budget (validation-chosen): "
                  f"{tier_fraction_benefit:.1%} promoted/demoted")

    ofr_uniform   = np.zeros(n_runs)
    ofr_oracle    = np.zeros(n_runs)
    ofr_xgb_cal   = np.zeros(n_runs)
    ofr_xgb_raw   = np.zeros(n_runs)
    ofr_gc_dev    = np.zeros(n_runs)
    ofr_hp        = np.zeros(n_runs)
    ofr_composite = np.zeros(n_runs)
    ofr_random    = np.zeros(n_runs)
    if have_deployable:
        ofr_xgb_cal_dep   = np.zeros(n_runs)
        ofr_gc_dev_dep    = np.zeros(n_runs)
        ofr_hp_dep        = np.zeros(n_runs)
        ofr_composite_dep = np.zeros(n_runs)
        ofr_random_dep    = np.zeros(n_runs)
    if have_benefit:
        ofr_benefit_dep = np.zeros(n_runs)

    for run_idx in range(n_runs):
        # One channel clone -> one byte-error array shared by all conditions (R3)
        run_channel = channel.clone(seed=base_seed + _EVAL_SEED_OFFSET + run_idx)
        byte_errors = _precompute_byte_errors(sequences, run_channel, coverage)

        ofr_uniform[run_idx]   = np.mean(byte_errors > (l_rs_uniform                  // 2))
        ofr_oracle[run_idx]    = np.mean(byte_errors > (l_rs_oracle                   // 2))
        ofr_xgb_cal[run_idx]   = np.mean(byte_errors > (l_rs_xgb_cal                  // 2))
        ofr_xgb_raw[run_idx]   = np.mean(byte_errors > (l_rs_xgb_raw                  // 2))
        ofr_gc_dev[run_idx]    = np.mean(byte_errors > (baseline_allocs['gc_dev']    // 2))
        ofr_hp[run_idx]        = np.mean(byte_errors > (baseline_allocs['hp']        // 2))
        ofr_composite[run_idx] = np.mean(byte_errors > (baseline_allocs['composite'] // 2))
        ofr_random[run_idx]    = np.mean(byte_errors > (baseline_allocs['random']    // 2))

        if have_deployable:
            ofr_xgb_cal_dep[run_idx]   = np.mean(byte_errors > (l_rs_xgb_cal_dep              // 2))
            ofr_gc_dev_dep[run_idx]    = np.mean(byte_errors > (baseline_allocs_dep['gc_dev']    // 2))
            ofr_hp_dep[run_idx]        = np.mean(byte_errors > (baseline_allocs_dep['hp']        // 2))
            ofr_composite_dep[run_idx] = np.mean(byte_errors > (baseline_allocs_dep['composite'] // 2))
            ofr_random_dep[run_idx]    = np.mean(byte_errors > (baseline_allocs_dep['random']    // 2))

        if have_benefit:
            ofr_benefit_dep[run_idx] = np.mean(byte_errors > (l_rs_benefit_dep // 2))

        if verbose and (run_idx + 1) % 5 == 0:
            print(f"  [allocation] Run {run_idx+1}/{n_runs} | "
                  f"uniform={ofr_uniform[:run_idx+1].mean():.4f} | "
                  f"oracle={ofr_oracle[:run_idx+1].mean():.4f} | "
                  f"composite={ofr_composite[:run_idx+1].mean():.4f} | "
                  f"xgb_cal={ofr_xgb_cal[:run_idx+1].mean():.4f}")

    results = {
        'ofr_uniform'   : ofr_uniform,
        'ofr_oracle'    : ofr_oracle,
        'ofr_xgb_cal'   : ofr_xgb_cal,
        'ofr_xgb_raw'   : ofr_xgb_raw,
        'ofr_gc_dev'    : ofr_gc_dev,
        'ofr_hp'        : ofr_hp,
        'ofr_composite' : ofr_composite,
        'ofr_random'    : ofr_random,
    }
    if have_deployable:
        results.update({
            'ofr_xgb_cal_deployable'  : ofr_xgb_cal_dep,
            'ofr_gc_dev_deployable'   : ofr_gc_dev_dep,
            'ofr_hp_deployable'       : ofr_hp_dep,
            'ofr_composite_deployable': ofr_composite_dep,
            'ofr_random_deployable'   : ofr_random_dep,
            'tier_fraction_deployable': np.array([tier_fraction_deployable]),
            'tier_fraction_oracle'    : np.array([tier_fraction]),
        })
    if have_benefit:
        results.update({
            'ofr_benefit_model_deployable': ofr_benefit_dep,
            'tier_fraction_benefit'       : np.array([tier_fraction_benefit]),
        })
    return results


# -- Delta-sensitivity sweep ---------------------------------------------------

def run_delta_sensitivity(
    sequences:         List[str],
    true_failure_freq: np.ndarray,
    calibrated_risk:   np.ndarray,
    channel,
    coverage:          int,
    l_rs_default:      int,
    delta_values:      List[int],
    n_runs:            int = 30,
    base_seed:         int = 0,
    l_rs_min:          int = 4,
    l_rs_max:          int = 16,
) -> Dict[int, Dict[str, np.ndarray]]:
    """OFR vs. delta sweep for calibrated XGBoost and true marginal-benefit oracle.

    R2 fix: oracle uses marginal_benefits recomputed for each delta value.
    R3 fix: byte errors pre-computed once per (run, delta), shared across conditions.
    R10 fix: four rule-based baselines added at each delta value.
    Seed ranges are non-overlapping between delta values (offset by delta * 100).

    Returns
    -------
    dict keyed by delta, each with arrays 'ofr_xgb_cal', 'ofr_oracle', 'ofr_uniform',
    'ofr_gc_dev', 'ofr_hp', 'ofr_composite', 'ofr_random'.
    """
    from mechanism import AllocationMechanism, uniform_allocation, oracle_allocation_greedy_swap
    from baselines import get_baseline_allocations

    N       = len(sequences)
    results = {}

    for delta in delta_values:
        print(f"  [delta_sensitivity] delta={delta}")

        # R2: marginal benefits depend on delta — recompute for each sweep value.
        # Use oracle_seed_offset = _ORACLE_SEED_OFFSET + delta*100 to avoid
        # seed overlap across delta values and with the main experiment oracle.
        marginal_benefits = estimate_marginal_benefits(
            sequences, true_failure_freq, channel, coverage,
            l_rs_default, delta, n_runs,
            base_seed=base_seed,
            oracle_seed_offset=_ORACLE_SEED_OFFSET + delta * 100,
            l_rs_max=l_rs_max,
        )
        # R4: symmetric marginal harm, non-overlapping seed range per delta.
        marginal_harm = estimate_marginal_harm(
            sequences, true_failure_freq, channel, coverage,
            l_rs_default, delta, n_runs,
            base_seed=base_seed,
            harm_seed_offset=_ORACLE_HARM_SEED_OFFSET + delta * 100,
            l_rs_min=l_rs_min,
        )

        alloc_mech = AllocationMechanism(l_rs_default, delta, l_rs_min, l_rs_max)
        l_rs_ora, n_star = oracle_allocation_greedy_swap(
            marginal_benefits, marginal_harm, l_rs_default, delta, l_rs_min, l_rs_max,
            n_runs=n_runs,
        )
        tier_fraction = n_star / N if N > 0 else 0.0
        l_rs_xgb   = alloc_mech.allocate(calibrated_risk, tier_fraction=tier_fraction)
        l_rs_uni   = uniform_allocation(N, l_rs_default)

        # R10: baselines computed from sequence features — same sequences, delta varies
        baseline_allocs = get_baseline_allocations(
            sequences, l_rs_default, delta, l_rs_min, l_rs_max,
            random_seed=base_seed + 8000 + delta * 100, tier_fraction=tier_fraction,
        )

        ofr_xgb = np.zeros(n_runs)
        ofr_ora = np.zeros(n_runs)
        ofr_uni = np.zeros(n_runs)
        ofr_gc  = np.zeros(n_runs)
        ofr_hp_ = np.zeros(n_runs)
        ofr_cmp = np.zeros(n_runs)
        ofr_rnd = np.zeros(n_runs)

        for run_idx in range(n_runs):
            # R3: one noise realisation per run, reused across all conditions.
            # Offset by delta*100 to keep seeds non-overlapping across delta values.
            run_channel = channel.clone(
                seed=base_seed + _DELTA_SEED_OFFSET + delta * 100 + run_idx
            )
            byte_errors = _precompute_byte_errors(sequences, run_channel, coverage)

            ofr_xgb[run_idx] = np.mean(byte_errors > (l_rs_xgb                   // 2))
            ofr_ora[run_idx] = np.mean(byte_errors > (l_rs_ora                    // 2))
            ofr_uni[run_idx] = np.mean(byte_errors > (l_rs_uni                    // 2))
            ofr_gc[run_idx]  = np.mean(byte_errors > (baseline_allocs['gc_dev']   // 2))
            ofr_hp_[run_idx] = np.mean(byte_errors > (baseline_allocs['hp']       // 2))
            ofr_cmp[run_idx] = np.mean(byte_errors > (baseline_allocs['composite']// 2))
            ofr_rnd[run_idx] = np.mean(byte_errors > (baseline_allocs['random']   // 2))

        results[delta] = {
            'ofr_xgb_cal'  : ofr_xgb,
            'ofr_oracle'   : ofr_ora,
            'ofr_uniform'  : ofr_uni,
            'ofr_gc_dev'   : ofr_gc,
            'ofr_hp'       : ofr_hp_,
            'ofr_composite': ofr_cmp,
            'ofr_random'   : ofr_rnd,
        }

    return results


# -- Persistence ---------------------------------------------------------------

def save_results(results: dict, out_path: str):
    """Save allocation experiment results as a compressed numpy archive."""
    np.savez_compressed(out_path, **{k: np.array(v) for k, v in results.items()
                                      if isinstance(v, (np.ndarray, list))})
    print(f"  [allocation] Saved to {out_path}")


