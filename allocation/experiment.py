def main():
    parser = argparse.ArgumentParser(
        description='Run allocation experiments for one dataset configuration.'
    )
    parser.add_argument('--config',     default='configs/experiment_config.yaml')
    parser.add_argument('--key',        required=True)
    parser.add_argument('--delta',      type=int, default=2)
    parser.add_argument('--n-runs',     type=int, default=None)
    parser.add_argument('--models-dir', default='models/saved/')
    parser.add_argument('--benefit-models-dir', default='models/saved_benefit/',
                         help='Part B benefit-aware models; used only when a '
                              'matching {key}_delta{delta}_benefit_model.pkl exists.')
    parser.add_argument('--out',        default='results/allocation/')
    args = parser.parse_args()

    with open(args.config) as f:
        cfg = yaml.safe_load(f)

    sys.path.insert(0, 'src')
    sys.path.insert(0, 'models')
    from dataset_assembler import load_dataset
    from channel_model import build_channel_from_config
    from train import load_models

    n_runs    = args.n_runs or cfg['allocation']['n_monte_carlo_runs']
    base_seed = cfg['random_seed']

    # Parse config key -> sub_rate, coverage
    parts     = args.key.split('_')
    sub_rate  = int(parts[0].replace('sub', '')) / 100
    coverage  = int(parts[1].replace('k', ''))

    print(f"[allocation] Loading {args.key} | delta={args.delta} | runs={n_runs}")
    X_tr, X_val, X_te, y_tr, y_val, y_te, feat_names = load_dataset(args.key, cfg)
    models = load_models(args.models_dir, args.key)

    # Calibrated risk: CalibratedModel.predict_proba returns [0,1] scores
    xgb_cal             = models.get('xgboost')
    calibrated_risk     = xgb_cal.predict_proba(X_te)  if xgb_cal else np.zeros(len(y_te))
    calibrated_risk_val = xgb_cal.predict_proba(X_val) if xgb_cal else np.zeros(len(y_val))

    # Raw (uncalibrated) risk: regressor .predict() after R1 fix (no predict_proba)
    if xgb_cal:
        raw_risk = np.clip(xgb_cal.base_model.predict(X_te), 0.0, 1.0)
    else:
        raw_risk = np.zeros(len(y_te))

    channel = build_channel_from_config(cfg, sub_rate, seed=base_seed)

    import pandas as pd
    data_path = os.path.join(cfg['paths']['datasets_dir'], f'{args.key}.parquet')
    df        = pd.read_parquet(data_path)
    splits    = pd.read_parquet(
        os.path.join(cfg['paths']['splits_dir'], f'{args.key}_splits.parquet')
    )
    test_idx      = splits[splits['split'] == 'test']['index'].values
    val_idx       = splits[splits['split'] == 'val']['index'].values
    sequences     = df['dna_sequence'].values[test_idx].tolist()
    sequences_val = df['dna_sequence'].values[val_idx].tolist()

    l_rs_default = cfg['sequence']['l_rs_default']
    l_rs_min     = cfg['rs']['l_rs_min']
    l_rs_max     = cfg['rs']['l_rs_max']

    # Paired oracle estimation (fix: one shared noise draw per run, evaluated
    # at low/default/high thresholds, instead of three independent simulations)
    print(f"[allocation] Estimating paired marginal benefit/harm (oracle) ...")
    marginal_benefits, marginal_harm = estimate_paired_marginal_effects(
        sequences, channel, coverage,
        l_rs_default, args.delta, n_runs,
        base_seed=base_seed,
        seed_offset=_ORACLE_SEED_OFFSET,
        l_rs_min=l_rs_min, l_rs_max=l_rs_max,
    )

    # Fairness fix: choose the deployable budget on validation data only,
    # before touching test data or the oracle's own privileged budget.
    print(f"[allocation] Selecting deployable tier_fraction on validation data ...")
    tier_fraction_deployable, val_ofr_by_tf = select_tier_fraction_on_validation(
        sequences_val, calibrated_risk_val, channel, coverage,
        l_rs_default, args.delta, l_rs_min, l_rs_max,
        n_runs=n_runs, base_seed=base_seed,
    )
    print(f"  [allocation] Validation OFR by candidate tier_fraction: "
          f"{ {k: round(v, 4) for k, v in val_ofr_by_tf.items()} }")

    # Part B: if a benefit-aware model exists for this exact key/delta, give it
    # the same fair treatment as the risk model -- its own validation-chosen
    # budget, no oracle or test-label information anywhere in the choice.
    benefit_model_path = os.path.join(
        args.benefit_models_dir, f'{args.key}_delta{args.delta}_benefit_model.pkl')
    benefit_scores = None
    tier_fraction_benefit = None
    if os.path.exists(benefit_model_path):
        import pickle
        print(f"[allocation] Found benefit-aware model -> {benefit_model_path}")
        with open(benefit_model_path, 'rb') as f:
            benefit_model = pickle.load(f)
        benefit_scores_val = benefit_model.predict(X_val)
        benefit_scores     = benefit_model.predict(X_te)
        print(f"[allocation] Selecting benefit-model tier_fraction on validation data ...")
        tier_fraction_benefit, val_ofr_by_tf_benefit = select_tier_fraction_on_validation(
            sequences_val, benefit_scores_val, channel, coverage,
            l_rs_default, args.delta, l_rs_min, l_rs_max,
            n_runs=n_runs, base_seed=base_seed,
        )
        print(f"  [allocation] Validation OFR by candidate tier_fraction (benefit model): "
              f"{ {k: round(v, 4) for k, v in val_ofr_by_tf_benefit.items()} }")
    else:
        print(f"[allocation] No benefit-aware model found for {args.key} delta={args.delta} "
              f"-- skipping the benefit-model condition.")

    os.makedirs(args.out, exist_ok=True)

    ofr_results = run_allocation_experiment(
        sequences, y_te, marginal_benefits, marginal_harm, calibrated_risk, raw_risk,
        channel, coverage, l_rs_default, args.delta,
        n_runs=n_runs, base_seed=base_seed,
        l_rs_min=l_rs_min, l_rs_max=l_rs_max,
        verbose=True,
        tier_fraction_deployable=tier_fraction_deployable,
        benefit_scores=benefit_scores,
        tier_fraction_benefit=tier_fraction_benefit,
    )

    out_path = os.path.join(args.out, f'{args.key}_delta{args.delta}')
    save_results(ofr_results, out_path)

    sys.path.insert(0, 'models')
    from evaluate import allocation_statistics
    stats = allocation_statistics(
        ofr_results['ofr_uniform'],
        ofr_results['ofr_xgb_cal'],
        ofr_results['ofr_oracle'],
    )
    print(f"\nResults for {args.key} | delta={args.delta}")
    for k, v in stats.items():
        print(f"  {k:<25}: {v:.4f}" if isinstance(v, float) else f"  {k:<25}: {v}")


if __name__ == '__main__':
    main()
