"""
allocation/experiment.py
========================
Runs the main allocation experiments (Layer 2 evaluation) across all 28
dataset configurations.

Experiment surface per the implementation plan:
  - 28 configs × 8 conditions × 30 runs = 6,720 main runs
  - 28 configs × 2 models × 3 delta values × 30 runs = 7,560 delta-sensitivity runs

Eight comparison conditions per config:
  1. UNIFORM    — baseline: equal L_RS for all sequences
  2. ORACLE     — true marginal-benefit oracle (R2 fix):
                  ranks by p_i(l_rs_default) - p_i(l_rs_default + delta)
  3. XGB_CAL   — calibrated XGBoost predictions
  4. XGB_RAW   — uncalibrated XGBoost outputs (shows why calibration matters)
  5. GC_DEV    — rule baseline: |gc_content - 0.5|  (R10 non-ML baseline)
  6. HP         — rule baseline: max homopolymer run length  (R10)
  7. COMPOSITE  — weighted GC-dev + HP rule  (R10; best non-ML competitor)
  8. RANDOM     — random allocation control  (R10; should ~= uniform)

R2 fix: the oracle now uses marginal-benefit ranking (Deltap_i = p(default) - p(default+delta))
instead of baseline failure_freq ranking.  A sequence in the over-failure regime that
already fails 90 % of the time at the default parity level may still fail 90 % at
default+delta — extra parity wastes the budget.  The marginal oracle promotes only
sequences where extra parity materially reduces failure probability.

R3 fix: all four conditions within each run share one pre-generated byte-error array
(common random numbers, CRN).  Previously each condition advanced the same channel RNG
sequentially, so uniform, oracle, xgb_cal, xgb_raw each saw different noise.  With CRN
the only difference between conditions is the parity allocation, making the paired
comparison valid.

Seed partitioning (relative to base_seed from config):
  0        ..  n_runs-1  — dataset / label generation (label_generator.py)
  1000     ..  1000+n_runs-1  — main allocation evaluation (EVAL_SEED_OFFSET)
  2000+d*100 .. 2000+d*100+n_runs-1  — delta-sensitivity evaluation per delta d
  3000     ..  3000+n_runs-1  — paired marginal-benefit/harm estimation
                                  (ORACLE_SEED_OFFSET; one shared noise draw per
                                  run evaluated at low/default/high thresholds --
                                  benefit and harm no longer use separate ranges)
  3000+d*100 .. 3000+d*100+n_runs-1  — delta-sensitivity oracle estimation per delta d
  9000     ..  9000+n_runs-1  — deployable tier_fraction selection on validation
                                  data (select_tier_fraction_on_validation)
  5000/5000+d*100 -- retired (was the independent marginal-harm range; harm
                                  is now paired with benefit under 3000, see above)

Usage (CLI):
    python allocation/experiment.py --config configs/experiment_config.yaml \\
        --key sub05_k30_simple --delta 2 --out results/allocation/
"""

